#!/usr/bin/env python3
"""Generate qml/Emoji.js from Unicode's emoji-test.txt.

Usage: tools/gen-emoji.py path/to/emoji-test.txt > qml/Emoji.js
Source: https://www.unicode.org/Public/emoji/latest/emoji-test.txt

Only fully-qualified emoji are used. Skin-tone variants are folded into their base
emoji (picked with a long press); the "Component" group (bare modifiers) is skipped.
"""
import json, re, sys

TONES = {0x1F3FB, 0x1F3FC, 0x1F3FD, 0x1F3FE, 0x1F3FF}
ICONS = {
    "Smileys & Emotion": "😀", "People & Body": "👋", "Animals & Nature": "🐶",
    "Food & Drink": "🍕", "Travel & Places": "🚗", "Activities": "⚽",
    "Objects": "💡", "Symbols": "❤️", "Flags": "🏁",
}

def main(path):
    version = date = ""
    groups, group = [], None
    line_re = re.compile(r"^([0-9A-F ]+?)\s*;\s*fully-qualified\s*#\s*\S+\s+E(\d+\.\d+)")
    for raw in open(path, encoding="utf-8"):
        if raw.startswith("# Version:"): version = raw.split(":", 1)[1].strip()
        if raw.startswith("# Date:"): date = raw.split(":", 1)[1].strip()
        if raw.startswith("# group:"):
            name = raw.split(":", 1)[1].strip()
            group = None if name == "Component" else {"name": name, "icon": ICONS.get(name, "?"), "emoji": [], "_index": {}}
            if group: groups.append(group)
            continue
        m = line_re.match(raw)
        if not m or not group:
            continue
        cps = [int(c, 16) for c in m.group(1).split()]
        text = "".join(map(chr, cps))
        ev = float(m.group(2))
        # match tone variants to their base ignoring U+FE0F (bases are written "🖐️",
        # their tone variants "🖐🏽" without the variation selector)
        key = "".join(chr(c) for c in cps if c not in TONES and c != 0xFE0F)
        if any(c in TONES for c in cps):
            idx = group["_index"].get(key)
            if idx is not None:
                group["emoji"][idx]["t"].append(text)
                continue
            # tone variant whose base isn't listed separately: keep as its own entry
        group["_index"].setdefault(key, len(group["emoji"]))
        group["emoji"].append({"e": text, "v": ev, "t": []})

    total = sum(1 + len(x["t"]) for g in groups for x in g["emoji"])
    out = [".pragma library", "",
           "// Generated by tools/gen-emoji.py from Unicode emoji-test.txt",
           "// Unicode Emoji %s (%s): %d fully-qualified emoji. Do not edit by hand." % (version, date, total),
           "// Each entry: e = emoji, v = emoji version, t = skin-tone variants (long press)",
           "var unicodeVersion = %s;" % json.dumps(version),
           "var categories = ["]
    for g in groups:
        items = []
        for x in g["emoji"]:
            item = {"e": x["e"], "v": x["v"]}
            if x["t"]: item["t"] = x["t"]
            items.append(item)
        out.append("    { name: %s, icon: %s, emoji: %s }," % (
            json.dumps(g["name"]), json.dumps(g["icon"], ensure_ascii=False),
            json.dumps(items, ensure_ascii=False, separators=(",", ":"))))
    out[-1] = out[-1].rstrip(",")
    out.append("];")
    sys.stdout.write("\n".join(out) + "\n")
    sys.stderr.write("Emoji %s: %d emoji, %d grid entries in %d categories\n" % (
        version, total, sum(len(g["emoji"]) for g in groups), len(groups)))

if __name__ == "__main__":
    main(sys.argv[1])
